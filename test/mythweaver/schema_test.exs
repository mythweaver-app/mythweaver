defmodule Mythweaver.SchemaTest do
  use Mythweaver.DataCase

  alias Mythweaver.Characters
  alias Mythweaver.Chats
  alias Mythweaver.Lore
  alias Mythweaver.Messages
  alias Mythweaver.Schema

  setup do
    %{scope: scope!()}
  end

  # The version nibble is the first character of the third hyphenated group.
  defp version(<<_::binary-size(14), version::binary-size(1), _::binary>>), do: version

  defp character!(scope, name) do
    {:ok, character} = Characters.create_character(scope, %{name: "#{name}-#{System.unique_integer([:positive])}"})
    character
  end

  describe "primary keys" do
    test "an inserted row gets a v7 id, not v4", %{scope: scope} do
      character = character!(scope, "Hero")

      assert version(character.id) == "7"
    end

    test "every context that inserts produces v7 ids", %{scope: scope} do
      hero = character!(scope, "Hero")
      foil = character!(scope, "Foil")

      {:ok, chat} =
        Chats.create_chat(scope, %{
          name: "chat-#{System.unique_integer([:positive])}",
          participants: [%{character_id: hero.id}, %{character_id: foil.id}],
          player_character_id: hero.id
        })

      {:ok, message} = Messages.send_message(scope, Chats.get_chat!(chat.id), hero.id, "Hello")
      {:ok, book} = Lore.create_book(scope, %{name: "book-#{System.unique_integer([:positive])}"})

      ids =
        [chat.id, hd(chat.participants).id, message.id, hd(message.bodies).id, book.id]

      assert Enum.map(ids, &version/1) == ["7", "7", "7", "7", "7"]
    end

    test "ids generated in the same millisecond still sort by creation", %{scope: scope} do
      ids = Enum.map(1..50, fn _i -> character!(scope, "Bulk").id end)

      assert ids == Enum.sort(ids)
    end

    test "generate_id/0 matches the autogenerated version, for insert_all callers", %{scope: scope} do
      assert version(Schema.generate_id()) == version(character!(scope, "Hero").id)
    end
  end
end
