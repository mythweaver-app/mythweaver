defmodule MythweaverWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :mythweaver

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  alias Phoenix.Ecto.CheckRepoStatus
  alias Phoenix.LiveDashboard.RequestLogger
  alias Phoenix.LiveView.Socket

  @session_options [
    store: :cookie,
    key: "_mythweaver_key",
    signing_salt: "Uxk/QOaH",
    same_site: "Lax",
    secure: Application.compile_env(:mythweaver, :secure_cookies, false)
  ]

  # Peer address, forwarding headers and user agent feed account fingerprints (`MythweaverWeb.Signals`).
  socket "/live", Socket,
    websocket: [connect_info: [:peer_data, :x_headers, :user_agent, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :x_headers, :user_agent, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :mythweaver,
    gzip: not code_reloading?,
    only: MythweaverWeb.static_paths(),
    # The root layout links these through `~p`, which digests them in prod (`favicon-<hash>.ico`).
    only_matching: ~w(favicon manifest),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug CheckRepoStatus, otp_app: :mythweaver
  end

  plug RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug MythweaverWeb.Router
end
