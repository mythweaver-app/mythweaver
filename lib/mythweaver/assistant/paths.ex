defmodule Mythweaver.Assistant.Paths do
  @moduledoc """
  App page paths for tool results, as plain strings: the core layer cannot use the web layer's
  verified routes. `test/mythweaver/assistant/paths_test.exs` checks each against the router.
  """

  def character(id), do: "/characters/#{id}/edit"
  def lore_book(id), do: "/lore/#{id}/edit"
  def lore_entry(id), do: "/lore/entries/#{id}/edit"
  def prompt(id), do: "/prompts/#{id}/edit"
  def prompt_block(id), do: "/prompts/blocks/#{id}/edit"
  def connection(id), do: "/ai/providers/#{id}/edit"
  def model(id), do: "/ai/models/#{id}/edit"
  def script(id), do: "/scripts/#{id}/edit"
  def tag(id), do: "/tags/#{id}/edit"
  def chat(id), do: "/chats/#{id}"
  def prompt_outlet(id), do: "/prompts/outlets/#{id}/edit"
  def memory_profile(id), do: "/memory/profiles/#{id}/edit"
  def side_prompt(id), do: "/memory/side-prompts/#{id}/edit"
  def side_prompt_set(id), do: "/memory/side-prompt-sets/#{id}/edit"
  def chat_memory(id), do: "/chats/#{id}/memory"
  def variable(id), do: "/variables/#{id}/edit"
  def expression_profile(id), do: "/characters/expression-profiles/#{id}/edit"
  def settings(category), do: "/settings/#{category}"

  @doc "The index pages, by name."
  def index(:characters), do: "/characters"
  def index(:lore), do: "/lore"
  def index(:prompts), do: "/prompts"
  def index(:prompt_blocks), do: "/prompts/blocks"
  def index(:connections), do: "/ai/providers"
  def index(:models), do: "/ai/models"
  def index(:tags), do: "/tags"
  def index(:settings), do: "/settings"
  def index(:jobs), do: "/jobs"
  def index(:import), do: "/import"
  def index(:prompt_outlets), do: "/prompts/outlets"
  def index(:memory_profiles), do: "/memory/profiles"
  def index(:side_prompts), do: "/memory/side-prompts"
  def index(:side_prompt_sets), do: "/memory/side-prompt-sets"
  def index(:variables), do: "/variables"
  def index(:scripts), do: "/scripts"
  def index(:expression_profiles), do: "/characters/expression-profiles"
  def index(:analytics), do: "/analytics"
end
